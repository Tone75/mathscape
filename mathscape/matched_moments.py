"""RQ-M05: analytic matched populations and one-series interval evaluation.

Both populations have theoretical mean zero, variance one and skewness two.
Realized samples are never restandardized. The arithmetic mean of X is the
target. K=1 estimates the finite-B procedure including its computational draw;
conditional endpoint SDs are unidentifiable and remain NaN for every method.
"""

import math
from numbers import Integral, Real

import numpy as np
from scipy import stats

from mathscape import stability

MAIN_NAMESPACE = 0x4D3035
SMOKE_NAMESPACE = 0x534D3035
DISTRIBUTIONS = ("gamma", "lognormal")
DISTRIBUTION_IDS = {"gamma": 1, "lognormal": 2}
METHODS = ("t", "percentile", "bca")
N = 20
B = 4999
K = 1
MAX_OUTER = 10_000
MAX_ID = 2**32 - 1
MAX_ELEMENTS = 1_000_000

# Analytic construction; no rounded numbers from the design table are used.
LOGNORMAL_V = 2 * math.sinh(math.asinh(1) / 3)
LOGNORMAL_T = 1 + LOGNORMAL_V**2
LOGNORMAL_S = math.sqrt(math.log1p(LOGNORMAL_V**2))
LOGNORMAL_M = math.sqrt(LOGNORMAL_T)
LOGNORMAL_D = LOGNORMAL_M * LOGNORMAL_V
LOGNORMAL_EXCESS_KURTOSIS = LOGNORMAL_T**4 + 2 * LOGNORMAL_T**3 + 3 * LOGNORMAL_T**2 - 6
LOGNORMAL_LOWER_BOUND = -1 / LOGNORMAL_V
LOGNORMAL_CONSTANTS = {"v": LOGNORMAL_V, "t": LOGNORMAL_T, "s": LOGNORMAL_S,
                       "m": LOGNORMAL_M, "d": LOGNORMAL_D}

prepare_sample = stability.prepare_sample
bootstrap_means = stability.bootstrap_means
mean_t_interval = stability.mean_t_interval
welch_interval = stability.welch_interval


def _integer(value, name, low, high):
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, Integral):
        raise ValueError(f"{name} must be an integer")
    if not low <= value <= high:
        raise ValueError(f"{name} must be between {low} and {high}")
    return int(value)


def _distribution(distribution):
    if not isinstance(distribution, str) or distribution not in DISTRIBUTION_IDS:
        raise ValueError("distribution must be gamma or lognormal")
    return distribution


def population_info(distribution):
    """Population facts for generation/plotting/evaluation, never inference."""
    distribution = _distribution(distribution)
    return {"mean": 0.0, "variance": 1.0, "skewness": 2.0,
            "excess_kurtosis": 6.0 if distribution == "gamma" else LOGNORMAL_EXCESS_KURTOSIS,
            "lower_bound": -1.0 if distribution == "gamma" else LOGNORMAL_LOWER_BOUND,
            "constants": {"shape": 1.0, "scale": 1.0} if distribution == "gamma" else LOGNORMAL_CONSTANTS.copy()}


def population_distribution(distribution):
    """Return the analytic standardized SciPy population for PDF/moment checks."""
    distribution = _distribution(distribution)
    if distribution == "gamma":
        return stats.gamma(a=1, loc=-1, scale=1)
    # Y~lognorm(s,scale=1); X=(Y-m)/d, not a log-mean target.
    return stats.lognorm(s=LOGNORMAL_S, loc=-LOGNORMAL_M / LOGNORMAL_D,
                         scale=1 / LOGNORMAL_D)


def validate_population_moments(tolerance=1e-10):
    """Deterministically check analytic moments/support via public SciPy mvsk.

    The default preregistered tolerance is an absolute 1e-10 for mean,
    variance and skewness, also enforced on excess kurtosis and support.
    Return actual/expected values and absolute errors, raising on mismatch.
    No samples or bootstrap draws are generated by this check.
    """
    if isinstance(tolerance, (bool, np.bool_)) or not isinstance(tolerance, Real):
        raise ValueError("tolerance must be finite and positive")
    try:
        tolerance = float(tolerance)
    except (OverflowError, ValueError) as exc:
        raise ValueError("tolerance must be finite and positive") from exc
    if not math.isfinite(tolerance) or tolerance <= 0:
        raise ValueError("tolerance must be finite and positive")
    checks = {}
    for distribution in DISTRIBUTIONS:
        population = population_distribution(distribution)
        reference = population_info(distribution)
        actual = dict(zip(("mean", "variance", "skewness", "excess_kurtosis"),
                          (float(value) for value in population.stats(moments="mvsk"))))
        actual["lower_bound"] = float(population.support()[0])
        expected = {key: reference[key] for key in actual}
        errors = {key: abs(actual[key] - expected[key]) for key in actual}
        passed = all(math.isfinite(value) and value <= tolerance for value in errors.values())
        checks[distribution] = {"actual": actual, "expected": expected,
                                "absolute_errors": errors, "tolerance": tolerance,
                                "passed": passed}
        if not passed:
            raise ValueError(f"analytic population moment check failed: {distribution}")
    return checks


def rng_for_panel(
    distribution, n=20, master_seed=0, outer_id=0, purpose_id=0, inner_id=0,
    namespace=MAIN_NAMESPACE,
):
    """PCG64 key=(namespace,population ID,20,outer,purpose,0), seed entropy.

    Gamma ID=1, lognormal ID=2; original purpose=0, bootstrap purpose=1.
    Outer=0..9999; inner=0 only. B, method, UI state and batching are absent.
    Different populations are independent groups even at matching outer IDs.
    """
    distribution = _distribution(distribution)
    n = _integer(n, "n", N, N)
    master_seed = _integer(master_seed, "master_seed", 0, MAX_ID)
    outer_id = _integer(outer_id, "outer_id", 0, MAX_OUTER - 1)
    purpose_id = _integer(purpose_id, "purpose_id", 0, 1)
    inner_id = _integer(inner_id, "inner_id", 0, 0)
    namespace = _integer(namespace, "namespace", 0, MAX_ID)
    sequence = np.random.SeedSequence(entropy=master_seed,
        spawn_key=(namespace, DISTRIBUTION_IDS[distribution], n, outer_id, purpose_id, inner_id))
    return np.random.Generator(np.random.PCG64(sequence))


def generate_sample(distribution, n=20, master_seed=0, outer_id=0, namespace=MAIN_NAMESPACE):
    """Generate one arithmetic-mean sample using fixed population constants."""
    rng = rng_for_panel(distribution, n, master_seed, outer_id, 0, 0, namespace)
    if distribution == "gamma":
        sample = rng.gamma(shape=1.0, scale=1.0, size=n) - 1.0
    else:
        z = rng.standard_normal(n)
        with np.errstate(over="ignore", invalid="ignore"):
            sample = (np.exp(LOGNORMAL_S * z) - LOGNORMAL_M) / LOGNORMAL_D
    if not np.isfinite(sample).all():
        raise ValueError("original_sample_nonfinite")
    return sample


def generate_bootstrap_means(
    sample, distribution, n=20, master_seed=0, outer_id=0, inner_id=0, Bmax=4999,
    namespace=MAIN_NAMESPACE, max_elements=MAX_ELEMENTS,
):
    rng = rng_for_panel(distribution, n, master_seed, outer_id, 1, inner_id, namespace)
    raw = np.asarray(sample)
    if raw.ndim != 1 or raw.size != n:
        raise ValueError("sample length and n disagree")
    return bootstrap_means(sample, rng, Bmax=Bmax, max_elements=max_elements)


def infer_single(context, means):
    """Evaluate the one supplied B distribution; no B-prefix comparison API.

    Production uses all 4,999 means, the sole development smoke uses 99.
    Smaller fixed reference arrays are supported without changing definitions.
    Invalid bootstrap inputs preserve t and carry the old reason-labelled
    invalid percentile/BCa records. Truth/population parameters are absent.
    """
    try:
        raw = np.asarray(means)
    except (TypeError, ValueError):
        raw = np.array(None)
    count = raw.size if raw.ndim == 1 and 1 <= raw.size <= B else 1
    return stability.infer_prefixes(context, means, B_values=(count,))[count]


def original_metrics(data):
    """Evaluate K1 endpoints with shape (3,) or (R,3), method last.

    Required arrays are lower/upper/valid/tail_warning. Every method uses one
    interval per original. Nonfinite/reversed/invalid endpoints remain NA for
    C/Mbelow/Mabove/T/width/warning; counts retain the single required interval.
    lower_sd/upper_sd/S/Ase/Apop are always NaN, including t: K1 provides no
    conditional endpoint-stability estimate, and no fictitious zero is used.
    """
    try:
        lower = np.asarray(data["lower"], dtype=float)
        upper = np.asarray(data["upper"], dtype=float)
        valid = np.asarray(data["valid"])
        warning = np.asarray(data["tail_warning"])
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError("data must contain lower/upper/valid/tail_warning") from exc
    if lower.ndim not in (1, 2) or lower.shape[-1] != len(METHODS):
        raise ValueError("K1 endpoint shape must be (3,) or (R,3)")
    if any(array.shape != lower.shape for array in (upper, valid, warning)) or valid.dtype.kind != "b" or warning.dtype.kind != "b":
        raise ValueError("endpoint and boolean-mask shapes must agree")
    with np.errstate(over="ignore", invalid="ignore"):
        width = upper - lower
    complete = valid & np.isfinite(lower) & np.isfinite(upper) & (lower <= upper) & np.isfinite(width)
    below, above = upper < 0, lower > 0
    result = {
        "complete": complete, "total_inner": np.ones(lower.shape, dtype=int),
        "valid_inner": complete.astype(int), "invalid_inner": (~complete).astype(int),
        "C": np.where(complete, (lower <= 0) & (0 <= upper), np.nan),
        "Mbelow": np.where(complete, below, np.nan),
        "Mabove": np.where(complete, above, np.nan),
        "T": np.where(complete, below.astype(int) - above.astype(int), np.nan),
        "mean_width": np.where(complete, width, np.nan),
        "warning_rate": np.where(complete, warning, np.nan),
    }
    result.update({key: np.full(lower.shape, np.nan) for key in ("lower_sd", "upper_sd", "S", "Ase", "Apop")})
    return result


def practical_difference_status(low, high, margin=0.01, complete=True):
    """Classify a 99% L-minus-G Welch interval using strict +/-margin bounds.

    There is no seed-sign gate. ``not_supported`` with equivalence_supported
    means practical equivalence within the preregistered margin for this one
    indicator/setting, not universal equivalence or a zero-difference proof.
    The caller must mark incomplete/invalid/undefined primary intervals via
    complete=False; conditional intervals must never drive this decision.
    """
    if isinstance(margin, (bool, np.bool_)) or not isinstance(margin, Real):
        raise ValueError("margin must be finite and positive")
    try:
        margin = float(margin)
    except (OverflowError, ValueError) as exc:
        raise ValueError("margin must be finite and positive") from exc
    if not math.isfinite(margin) or margin <= 0:
        raise ValueError("margin must be finite and positive")
    base = {"status": "inconclusive", "direction": "undetermined", "equivalence_supported": False}
    if not complete:
        return base | {"reason": "incomplete_or_undefined_primary_comparison"}
    try:
        finite = math.isfinite(low) and math.isfinite(high)
    except (TypeError, ValueError):
        finite = False
    if not finite or low >= high:
        return base | {"reason": "undefined_primary_interval"}
    if low > margin:
        return {"status": "supported", "direction": "positive", "equivalence_supported": False, "reason": ""}
    if high < -margin:
        return {"status": "supported", "direction": "negative", "equivalence_supported": False, "reason": ""}
    if low > -margin and high < margin:
        return {"status": "not_supported", "direction": "within_margin", "equivalence_supported": True, "reason": ""}
    return base | {"reason": "practical_margin_touched_or_crossed"}


def interval_status(low, high, valid=True, margin=0.01):
    """Convenience spelling with the interval helper's validity flag."""
    return practical_difference_status(low, high, margin=margin, complete=valid)
